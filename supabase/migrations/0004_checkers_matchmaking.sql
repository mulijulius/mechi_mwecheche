-- Checkers rule variants
create type public.checkers_variant as enum ('english', 'russian');

-- Checkers board/coin themes (mirrors ThemeManager THEMES keys in Modules.js)
create type public.checkers_theme as enum ('classic', 'green', 'midnight', 'red', 'ivory');

-- Contest lifecycle: open → booked → in_progress → completed | cancelled
create type public.contest_status as enum ('open', 'booked', 'in_progress', 'completed', 'cancelled');

-- ----------------------------------------------------------------------------
-- CHECKERS CONTESTS
-- A contest is a hosted checkers match with a specific variant, theme, and
-- optional entry fee. 'open' means the host is waiting for an opponent.
-- 'booked' means both seats are filled and locked — no more joiners.
-- ----------------------------------------------------------------------------

create table public.checkers_contests (
  id              uuid primary key default gen_random_uuid(),
  host_id         uuid not null references public.profiles (id) on delete cascade,
  variant         public.checkers_variant not null default 'english',
  theme           public.checkers_theme not null default 'classic',

  -- Entry fee in KES cents. 0 = Free Trial match.
  entry_fee_cents bigint not null default 0 check (entry_fee_cents >= 0),

  -- Accumulated pot. For a 2-player game: 0 (free) or 2 × entry_fee_cents.
  pot_cents       bigint not null default 0 check (pot_cents >= 0),

  status          public.contest_status not null default 'open',

  -- Winner set on completion; null if cancelled or draw.
  winner_id       uuid references public.profiles (id),

  -- Room code for direct invite (6-char uppercase alphanum). Generated by trigger.
  room_code       text not null unique,

  created_at      timestamptz not null default now(),
  booked_at       timestamptz,
  started_at      timestamptz,
  completed_at    timestamptz
);

comment on table public.checkers_contests is
  'Hosted checkers contests. Each row is one 1v1 match with variant + theme + stake.';

create index checkers_contests_status_idx    on public.checkers_contests (status);
create index checkers_contests_host_idx      on public.checkers_contests (host_id);
create index checkers_contests_created_idx   on public.checkers_contests (created_at desc);

-- ----------------------------------------------------------------------------
-- CHECKERS CONTEST PLAYERS
-- Exactly two rows per booked/in-progress contest: seat 0 = host, seat 1 = challenger.
-- ----------------------------------------------------------------------------

create table public.checkers_contest_players (
  id          uuid primary key default gen_random_uuid(),
  contest_id  uuid not null references public.checkers_contests (id) on delete cascade,
  user_id     uuid not null references public.profiles (id),
  seat        smallint not null check (seat in (0, 1)),  -- 0=host, 1=challenger
  color       text not null check (color in ('black', 'white')),
  joined_at   timestamptz not null default now(),
  unique (contest_id, user_id),
  unique (contest_id, seat)
);

comment on table public.checkers_contest_players is
  'Players seated in a checkers contest. Two rows max per contest (1v1).';

create index checkers_contest_players_contest_idx on public.checkers_contest_players (contest_id);
create index checkers_contest_players_user_idx    on public.checkers_contest_players (user_id);

-- ----------------------------------------------------------------------------
-- DAILY TRIAL QUOTAS
-- Server-side enforced daily free-match limit: 3 per user per variant per day.
-- The client-side TrialManager in Modules.js tracks this locally; this table
-- is the authoritative server-side mirror used for verification before booking.
-- ----------------------------------------------------------------------------

create table public.checkers_trial_usage (
  id          uuid primary key default gen_random_uuid(),
  user_id     uuid not null references public.profiles (id) on delete cascade,
  variant     public.checkers_variant not null,
  usage_date  date not null default current_date,
  match_count smallint not null default 0 check (match_count >= 0),
  unique (user_id, variant, usage_date)
);

comment on table public.checkers_trial_usage is
  'Tracks how many free trial matches a user has played per variant per day. Max 3.';

create index checkers_trial_usage_user_date_idx
  on public.checkers_trial_usage (user_id, usage_date);

