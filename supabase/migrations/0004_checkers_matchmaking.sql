-- Contests: everyone can read open/booked contests; only host or admin updates
create policy "Checkers contests viewable by all"
  on public.checkers_contests for select using (true);

create policy "Authenticated users can host a contest"
  on public.checkers_contests for insert
  with check (auth.uid() = host_id);

create policy "Host or admin can update contest"
  on public.checkers_contests for update
  using (auth.uid() = host_id or public.is_admin());

-- Players: everyone reads, own rows only for insert
create policy "Contest players viewable by all"
  on public.checkers_contest_players for select using (true);

create policy "Users can seat themselves"
  on public.checkers_contest_players for insert
  with check (auth.uid() = user_id);

-- Trial usage: own rows only
create policy "Users can view their own trial usage"
  on public.checkers_trial_usage for select
  using (auth.uid() = user_id);

