  on public.ludo_contests for select using (true);

create policy "Authenticated users can host a ludo contest"
  on public.ludo_contests for insert
  with check (auth.uid() = host_id);

create policy "Host or admin can update ludo contest"
  on public.ludo_contests for update
  using (auth.uid() = host_id or public.is_admin());

create policy "Ludo contest players viewable by all"
  on public.ludo_contest_players for select using (true);

create policy "Users can seat themselves in ludo"
  on public.ludo_contest_players for insert
  with check (auth.uid() = user_id);

create policy "Users can view their own ludo trial usage"
  on public.ludo_trial_usage for select
  using (auth.uid() = user_id);

