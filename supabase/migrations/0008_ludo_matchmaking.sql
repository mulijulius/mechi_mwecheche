-- ============================================================================
-- Migration: 0008_ludo_matchmaking.sql
-- Purpose:   Variant/theme manager, matchmaking, wallet verification, booking
--            system, daily trial quota, and leave/forfeit handling for the
--            Ludo game integration.
--
-- This intentionally mirrors the structure of 0004_checkers_matchmaking.sql
-- and 0005_checkers_leave_forfeit.sql as closely as the game shape allows.
-- The main structural difference from checkers: a Ludo contest seats 2-4
-- players (not a fixed 1v1), so `max_players` is chosen by the host and the
-- contest only flips from 'open' to 'booked' once every seat is filled.
-- Reuses public.contest_status (defined in 0004_checkers_matchmaking.sql) —
-- the lifecycle (open → booked → in_progress → completed | cancelled) is
-- identical, so no new enum is created for it.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- ENUM EXTENSIONS
-- ----------------------------------------------------------------------------

-- Ludo board/token themes (mirrors ThemeManager THEMES keys in public/ludo/js/Modules.js)
create type public.ludo_theme as enum ('classic', 'royal', 'sunset', 'ocean');

-- Token colors, in fixed turn order (matches COLORS in public/ludo/js/GameEngine.js)
create type public.ludo_color as enum ('red', 'green', 'yellow', 'blue');

-- ----------------------------------------------------------------------------
-- LUDO CONTESTS
-- A contest is a hosted Ludo match for 2-4 players with a theme and optional
-- entry fee. 'open' means the host is still waiting for seats to fill.
-- 'booked' means every seat (max_players) is filled and locked.
-- ----------------------------------------------------------------------------

create table public.ludo_contests (
  id              uuid primary key default gen_random_uuid(),
  host_id         uuid not null references public.profiles (id) on delete cascade,
  theme           public.ludo_theme not null default 'classic',
  max_players     smallint not null default 4 check (max_players in (2, 3, 4)),

  -- Entry fee in KES cents. 0 = Free Trial match.
  entry_fee_cents bigint not null default 0 check (entry_fee_cents >= 0),

  -- Accumulated pot. For a free match: 0. Otherwise entry_fee_cents × seated players.
  pot_cents       bigint not null default 0 check (pot_cents >= 0),

  status          public.contest_status not null default 'open',

  -- Winner set on completion; null if cancelled.
  winner_id       uuid references public.profiles (id),

  -- Set when a seated player leaves an open/booked/in_progress contest.
  forfeited_by    uuid references public.profiles (id),

  -- Room code for direct invite (6-char uppercase alphanum). Generated by trigger.
  room_code       text not null unique,

  created_at      timestamptz not null default now(),
  booked_at       timestamptz,
  started_at      timestamptz,
  completed_at    timestamptz
);

comment on table public.ludo_contests is
  'Hosted Ludo contests. Each row is one 2-4 player match with theme + stake.';

create index ludo_contests_status_idx    on public.ludo_contests (status);
create index ludo_contests_host_idx      on public.ludo_contests (host_id);
create index ludo_contests_created_idx   on public.ludo_contests (created_at desc);

-- ----------------------------------------------------------------------------
-- LUDO CONTEST PLAYERS
-- Up to four rows per contest. seat 0 = host (always 'red'), seats 1-3 fill
-- in join order with 'green', 'yellow', 'blue' respectively.
-- ----------------------------------------------------------------------------

create table public.ludo_contest_players (
  id          uuid primary key default gen_random_uuid(),
  contest_id  uuid not null references public.ludo_contests (id) on delete cascade,
  user_id     uuid not null references public.profiles (id),
  seat        smallint not null check (seat in (0, 1, 2, 3)),
  color       public.ludo_color not null,
  left_at     timestamptz,  -- set when this player forfeits mid-match
  joined_at   timestamptz not null default now(),
  unique (contest_id, user_id),
  unique (contest_id, seat)
);

comment on table public.ludo_contest_players is
  'Players seated in a Ludo contest. Up to four rows per contest.';

create index ludo_contest_players_contest_idx on public.ludo_contest_players (contest_id);
create index ludo_contest_players_user_idx    on public.ludo_contest_players (user_id);

-- ----------------------------------------------------------------------------
-- DAILY TRIAL QUOTAS
-- Server-side enforced daily free-match limit: 3 per user per day for Ludo
-- (no variant split, unlike checkers' english/russian — Ludo has one ruleset).
-- ----------------------------------------------------------------------------

create table public.ludo_trial_usage (
  id          uuid primary key default gen_random_uuid(),
  user_id     uuid not null references public.profiles (id) on delete cascade,
  usage_date  date not null default current_date,
  match_count smallint not null default 0 check (match_count >= 0),
  unique (user_id, usage_date)
);

comment on table public.ludo_trial_usage is
  'Tracks how many free trial Ludo matches a user has played per day. Max 3.';

create index ludo_trial_usage_user_date_idx
  on public.ludo_trial_usage (user_id, usage_date);

